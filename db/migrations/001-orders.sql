-- Additive application metadata. Existing Adminium tables and rows are preserved.
CREATE SCHEMA IF NOT EXISTS print_shop;

CREATE TABLE IF NOT EXISTS print_shop.customer_sessions (
  token_hash text PRIMARY KEY,
  expires_at bigint NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS print_shop.orders (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ref text NOT NULL UNIQUE,
  owner_session_hash text NOT NULL REFERENCES print_shop.customer_sessions(token_hash),
  request_key text NOT NULL,
  payload_hash text NOT NULL,
  snapshot jsonb NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE (owner_session_hash, request_key)
);
CREATE INDEX IF NOT EXISTS orders_owner_idx ON print_shop.orders(owner_session_hash);

CREATE SEQUENCE IF NOT EXISTS print_shop.reference_seq;
ALTER TABLE public.jobs ADD COLUMN IF NOT EXISTS order_id bigint REFERENCES print_shop.orders(id);
ALTER TABLE public.jobs ADD COLUMN IF NOT EXISTS revision integer NOT NULL DEFAULT 0;
CREATE INDEX IF NOT EXISTS jobs_order_idx ON public.jobs(order_id);

CREATE TABLE IF NOT EXISTS print_shop.staff (
  id text PRIMARY KEY,
  email text NOT NULL,
  password_hash text NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX IF NOT EXISTS staff_email_idx ON print_shop.staff(lower(email));
CREATE TABLE IF NOT EXISTS print_shop.staff_sessions (
  token_hash text PRIMARY KEY,
  staff_id text NOT NULL REFERENCES print_shop.staff(id) ON DELETE CASCADE,
  expires_at bigint NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS print_shop.schema_migrations (
  version integer PRIMARY KEY,
  applied_at timestamptz NOT NULL DEFAULT now()
);
INSERT INTO print_shop.schema_migrations(version) VALUES (1) ON CONFLICT DO NOTHING;
